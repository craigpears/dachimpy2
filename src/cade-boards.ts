/** One of the real boards, by its id (`Lilac1_1`, `Gallows16_3`...). */
export function cadeBoard(id: string): Board {
  const b = CADE_BOARDS[id];
  if (!b) throw new Error(`No board "${id}"`);
  return boardFromText(b.rows, b.name);
}
